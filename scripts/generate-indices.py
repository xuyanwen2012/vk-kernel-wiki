#!/usr/bin/env python3
"""Generate query index pages from YAML frontmatter in sources/ and wiki/.

Writes queries/by-*.md under the wiki root. Every index is always generated,
including for an empty wiki (tables then hold a single `_None_` row).

Usage:
    generate-indices.py
"""

import re
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _yaml_compat import yaml  # noqa: E402
from _wiki_root import WIKI_ROOT  # noqa: E402
import arch_policy  # noqa: E402

REPO_ROOT = WIKI_ROOT
SOURCES_DIR = REPO_ROOT / "sources"
WIKI_DIR = REPO_ROOT / "wiki"
QUERIES_DIR = REPO_ROOT / "queries"
MEASUREMENTS_PREFIX = "sources/measurements/"

HEADER_NOTE = "> Auto-generated by scripts/generate-indices.py. Do not edit manually."


def extract_frontmatter(filepath):
    with open(filepath, encoding="utf-8") as f:
        content = f.read()
    match = re.match(r'^---\s*\r?\n(.*?)\r?\n---\s*\r?\n', content, re.DOTALL)
    if not match:
        return None
    try:
        return yaml.safe_load(match.group(1))
    except yaml.YAMLError:
        return None


def qlink(path):
    """Make a link relative from the queries/ directory."""
    return f"../{path}"


def as_list(value):
    """Frontmatter list fields may be absent, null, or a bare scalar."""
    if value is None:
        return []
    if isinstance(value, (list, tuple, set)):
        return list(value)
    return [value]


def cell(value):
    """Render a value safely inside a markdown table cell."""
    return str(value).replace("|", "\\|").replace("\n", " ").strip()


def none_row(columns):
    """A placeholder row for an empty table with the given column count."""
    return "| _None_ |" + " |" * (columns - 1)


def load_tag_group(group):
    """Load one controlled-vocabulary group from data/tags.yaml as a set."""
    tags_path = REPO_ROOT / "data" / "tags.yaml"
    if not tags_path.exists():
        return set()
    with open(tags_path, encoding="utf-8") as f:
        data = yaml.safe_load(f) or {}
    if not isinstance(data, dict):
        return set()
    return {str(v) for v in as_list(data.get(group))}


def page_link(page):
    title = cell(page.get("title", page.get("id", "Untitled")))
    return f"[{title}]({qlink(page['_path'])})"


def unique_links(pages):
    links = []
    seen = set()
    for p in pages:
        pid = p.get("id", p.get("_path", ""))
        if pid not in seen:
            seen.add(pid)
            links.append(page_link(p))
    return links


def collect_all_pages():
    pages = []
    errors = []
    for search_dir in [SOURCES_DIR, WIKI_DIR]:
        if not search_dir.exists():
            continue
        for md_file in sorted(search_dir.rglob("*.md")):
            rel = md_file.relative_to(REPO_ROOT).as_posix()
            try:
                fm = extract_frontmatter(md_file)
            except UnicodeDecodeError:
                errors.append(f"{rel}: not valid UTF-8")
                continue
            except OSError as exc:
                errors.append(f"{rel}: unreadable ({exc.strerror or exc})")
                continue
            if fm is None:
                errors.append(f"{rel}: missing or unparseable frontmatter")
            elif not isinstance(fm, dict):
                errors.append(f"{rel}: frontmatter is {type(fm).__name__}, not a mapping")
            else:
                fm["_path"] = rel
                fm["_dir"] = search_dir.relative_to(REPO_ROOT).as_posix()
                pages.append(fm)
    if errors:
        print(f"ERROR: {len(errors)} file(s) are unreadable or have missing/unparseable frontmatter:")
        for e in errors:
            print(f"  {e}")
        print("Run python3 scripts/validate.py first to fix these files.")
        sys.exit(1)
    return pages


def generate_by_problem(pages):
    # Build id -> page map for resolving technique IDs to links
    id_map = {p["id"]: p for p in pages if "id" in p}

    lines = [
        "# Query: By Problem / Symptom",
        "",
        HEADER_NOTE,
        "",
        "| Symptom | Pattern Page | Candidate Techniques | Sources |",
        "|---------|-------------|---------------------|---------|",
    ]
    patterns = sorted(
        (p for p in pages if p.get("type") == "pattern"),
        key=lambda x: str(x.get("title", "")),
    )
    for p in patterns:
        symptoms = ", ".join(cell(s) for s in as_list(p.get("symptoms")))
        # Resolve technique IDs to clickable links
        tech_links = []
        for tid in as_list(p.get("candidate_techniques")):
            if tid in id_map:
                tech_links.append(page_link(id_map[tid]))
            else:
                tech_links.append(cell(tid))
        techniques = ", ".join(tech_links)
        src_count = len(as_list(p.get("sources")))
        lines.append(f"| {symptoms} | {page_link(p)} | {techniques} | {src_count} sources |")
    if not patterns:
        lines.append(none_row(4))
    return "\n".join(lines) + "\n"


def generate_by_technique(pages):
    lines = [
        "# Query: By Technique",
        "",
        HEADER_NOTE,
        "",
        "| Technique | Tags | Architectures | Confidence | Reproducibility | Sources |",
        "|-----------|------|--------------|------------|-----------------|---------|",
    ]
    techniques = sorted(
        (p for p in pages if p.get("type") == "technique"),
        key=lambda x: str(x.get("title", "")),
    )
    for t in techniques:
        tags = ", ".join(cell(v) for v in as_list(t.get("tags"))[:4])
        archs = ", ".join(cell(v) for v in as_list(t.get("architectures")))
        conf = cell(t.get("confidence", ""))
        repro = cell(t.get("reproducibility", ""))
        src_count = len(as_list(t.get("sources")))
        lines.append(f"| {page_link(t)} | {tags} | {archs} | {conf} | {repro} | {src_count} |")
    if not techniques:
        lines.append(none_row(6))
    return "\n".join(lines) + "\n"


def generate_by_hardware_feature(pages):
    lines = [
        "# Query: By Hardware Feature",
        "",
        HEADER_NOTE,
        "",
    ]
    hw_tag_set = load_tag_group("hardware_features")

    # Merge explicit hardware_features AND supplemental hw tags (deduplicated)
    feature_pages = defaultdict(list)
    for p in pages:
        indexed = set()
        for feat in as_list(p.get("hardware_features")):
            feature_pages[feat].append(p)
            indexed.add(feat)
        for tag in as_list(p.get("tags")):
            if tag in hw_tag_set and tag not in indexed:
                feature_pages[tag].append(p)
                indexed.add(tag)

    lines.append("| Feature | Related Pages |")
    lines.append("|---------|--------------|")
    for feat in sorted(feature_pages.keys(), key=str):
        lines.append(f"| `{cell(feat)}` | {', '.join(unique_links(feature_pages[feat]))} |")
    if not feature_pages:
        lines.append(none_row(2))
    return "\n".join(lines) + "\n"


def generate_by_repo(pages):
    lines = [
        "# Query: By Repository",
        "",
        HEADER_NOTE,
        "",
    ]
    repos = defaultdict(list)
    for p in pages:
        if "repo" in p and "pr" in p:
            repos[str(p["repo"])].append(p)

    columns = ["| PR | Title | Date | Techniques | Tags |",
               "|-----|-------|------|------------|------|"]
    for repo in sorted(repos.keys()):
        prs = sorted(repos[repo], key=lambda x: str(x.get("date", "")), reverse=True)
        # Real HTML anchor so fragment links work in any renderer
        slug = repo.lower().replace("/", "")
        lines.append(f'<a id="{slug}"></a>')
        lines.append(f"## {repo}")
        lines.append(f"{len(prs)} PRs")
        lines.append("")
        lines.extend(columns)
        for pr in prs:
            pr_num = pr.get("pr", "?")
            title = cell(pr.get("title", "Untitled"))
            date = cell(pr.get("date", ""))
            path = qlink(pr["_path"])
            techniques = ", ".join(cell(v) for v in list(dict.fromkeys(as_list(pr.get("techniques"))))[:3])
            tags = ", ".join(cell(v) for v in list(dict.fromkeys(as_list(pr.get("tags"))))[:3])
            lines.append(f"| [#{pr_num}]({path}) | {title} | {date} | {techniques} | {tags} |")
        lines.append("")
    if not repos:
        lines.extend(columns)
        lines.append(none_row(5))
    return "\n".join(lines) + "\n"


def generate_by_kernel_type(pages):
    lines = [
        "# Query: By Kernel Type",
        "",
        HEADER_NOTE,
        "",
        "| Kernel Type | Pages |",
        "|-------------|-------|",
    ]
    kt_tag_set = load_tag_group("kernel_types")

    # Explicit kernel_types is authoritative; tags only when field is absent/empty
    kernel_bearing_types = {"kernel", None}
    type_pages = defaultdict(list)
    for p in pages:
        explicit = as_list(p.get("kernel_types"))
        if explicit:
            for kt in explicit:
                type_pages[kt].append(p)
        elif p.get("type") in kernel_bearing_types:
            for tag in as_list(p.get("tags")):
                if tag in kt_tag_set:
                    type_pages[tag].append(p)

    for kt in sorted(type_pages.keys(), key=str):
        lines.append(f"| `{cell(kt)}` | {', '.join(unique_links(type_pages[kt]))} |")
    if not type_pages:
        lines.append(none_row(2))
    return "\n".join(lines) + "\n"


def generate_by_language(pages):
    lines = [
        "# Query: By Language",
        "",
        HEADER_NOTE,
        "",
    ]
    valid_langs = load_tag_group("languages")

    # Map: canonical language tag -> {guide: page, consumers: [pages]}
    lang_data = {}
    for lang in sorted(valid_langs):
        lang_data[lang] = {"guide": None, "consumers": []}

    # Find dedicated language guide pages
    # Match by: first tag that's a valid language, OR id-derived tag as fallback
    for p in pages:
        if p.get("type") == "language":
            primary_lang = None
            for tag in as_list(p.get("tags")):
                if tag in valid_langs:
                    primary_lang = tag
                    break
            # Fallback: derive from id (lang-glsl -> glsl)
            if not primary_lang:
                lang_id = str(p.get("id", ""))
                if lang_id.startswith("lang-") and lang_id[5:] in valid_langs:
                    primary_lang = lang_id[5:]
            if primary_lang and primary_lang in lang_data:
                lang_data[primary_lang]["guide"] = p

    # Explicit languages is authoritative; tags only when field is absent/empty
    for p in pages:
        if p.get("type") != "language":
            explicit = as_list(p.get("languages"))
            if explicit:
                for lang in explicit:
                    if lang in lang_data:
                        lang_data[lang]["consumers"].append(p)
            else:
                for tag in as_list(p.get("tags")):
                    if tag in valid_langs:
                        lang_data[tag]["consumers"].append(p)

    lines.append("| Language | Guide | Related Pages |")
    lines.append("|----------|-------|--------------|")

    rows = 0
    for lang in sorted(lang_data.keys()):
        data = lang_data[lang]
        if not data["guide"] and not data["consumers"]:
            continue
        guide_link = page_link(data["guide"]) if data["guide"] else ""
        lines.append(f"| `{lang}` | {guide_link} | {', '.join(unique_links(data['consumers']))} |")
        rows += 1
    if not rows:
        lines.append(none_row(3))

    return "\n".join(lines) + "\n"


def _architecture_page_table(lines, pages):
    lines.extend(["| Page | Path |", "|------|------|"])
    for page in sorted(pages, key=lambda value: value.get("_path", "")):
        lines.append(f"| {page_link(page)} | `{page['_path']}` |")
    if not pages:
        lines.append(none_row(2))
    lines.append("")


def generate_by_architecture(pages):
    """Tree-ordered architecture index: per node, the pages tagged exactly with it."""
    exact = defaultdict(list)
    for page in pages:
        for value in dict.fromkeys(arch_policy.normalize(v) for v in as_list(page.get("architectures"))):
            exact[value].append(page)

    lines = [
        "# Query: By Architecture",
        "",
        HEADER_NOTE + " Nodes follow the tree in `data/architectures.yaml`. "
        "Each section lists only the pages tagged with exactly that node; pages tagged "
        "with a descendant appear under the descendant, and pages tagged only with an "
        "ancestor are not repeated under its descendants. "
        "`scripts/query.py --architecture <node>` returns a node together with its descendants.",
        "",
    ]
    order = arch_policy.tree_order()
    for name, depth, kind in order:
        lines.extend([f"{'#' * min(depth + 2, 6)} `{name}` ({kind})", ""])
        parents = arch_policy.ancestors(name)
        if parents:
            lines.extend([f"Path: {' > '.join(f'`{n}`' for n in reversed(parents))} > `{name}`", ""])
        _architecture_page_table(lines, exact.get(name, []))
    if not order:
        lines.extend(["_No architecture nodes are defined in `data/architectures.yaml`._", ""])
        _architecture_page_table(lines, [])

    known = {name for name, _, _ in order}
    unrecognized = sorted(value for value in exact if value not in known)
    if unrecognized:
        lines.extend([
            "## Unrecognized values",
            "",
            "Values that are not nodes of `data/architectures.yaml`; `scripts/validate.py` rejects these.",
            "",
        ])
        for value in unrecognized:
            lines.extend([f"### `{cell(value)}`", ""])
            _architecture_page_table(lines, exact[value])
    return "\n".join(lines).rstrip("\n") + "\n"


def _measurement_table(lines, pages):
    lines.extend([
        "| Measurement | Driver | Measured at | Path |",
        "|-------------|--------|-------------|------|",
    ])
    ordered = sorted(
        pages,
        key=lambda p: (str(p.get("measured_at", "")), p.get("_path", "")),
        reverse=True,
    )
    for page in ordered:
        driver = cell(page.get("driver", ""))
        measured_at = cell(page.get("measured_at", ""))
        lines.append(f"| {page_link(page)} | {driver} | {measured_at} | `{page['_path']}` |")
    if not pages:
        lines.append(none_row(4))
    lines.append("")


def generate_by_device(pages):
    """First-party measurement pages per device node, newest first."""
    by_device = defaultdict(list)
    for page in pages:
        if page["_path"].startswith(MEASUREMENTS_PREFIX):
            by_device[arch_policy.normalize(page.get("device", ""))].append(page)

    lines = [
        "# Query: By Device",
        "",
        HEADER_NOTE + " Lists `source-measurement` pages (`sources/measurements/`) "
        "under the exact device node named by their `device` field, newest first. "
        "Devices follow the tree in `data/architectures.yaml`.",
        "",
    ]
    device_nodes = arch_policy.devices()
    for name in device_nodes:
        parents = arch_policy.ancestors(name)
        lines.extend([f"## `{name}`", ""])
        if parents:
            lines.extend([f"Path: {' > '.join(f'`{n}`' for n in reversed(parents))} > `{name}`", ""])
        _measurement_table(lines, by_device.get(name, []))
    if not device_nodes:
        lines.extend(["_No device nodes are defined in `data/architectures.yaml`._", ""])
        _measurement_table(lines, [])

    unrecognized = sorted(value for value in by_device if value not in set(device_nodes))
    if unrecognized:
        lines.extend([
            "## Unrecognized devices",
            "",
            "Measurement pages whose `device` is not a device node of "
            "`data/architectures.yaml`; `scripts/validate.py` rejects these.",
            "",
        ])
        for value in unrecognized:
            lines.extend([f"### `{cell(value) or '(missing)'}`", ""])
            _measurement_table(lines, by_device[value])
    return "\n".join(lines).rstrip("\n") + "\n"


GENERATORS = {
    "by-architecture.md": generate_by_architecture,
    "by-device.md": generate_by_device,
    "by-problem.md": generate_by_problem,
    "by-technique.md": generate_by_technique,
    "by-hardware-feature.md": generate_by_hardware_feature,
    "by-repo.md": generate_by_repo,
    "by-kernel-type.md": generate_by_kernel_type,
    "by-language.md": generate_by_language,
}


def main():
    try:
        arch_policy.load_tree()
    except arch_policy.ArchitectureTreeError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        sys.exit(2)

    QUERIES_DIR.mkdir(exist_ok=True)
    pages = collect_all_pages()
    print(f"Collected {len(pages)} pages from sources/ and wiki/")

    for filename, gen_func in GENERATORS.items():
        content = gen_func(pages)
        outpath = QUERIES_DIR / filename
        outpath.write_text(content, encoding="utf-8")
        print(f"  Generated {outpath.relative_to(REPO_ROOT)}")

    print("Done.")


if __name__ == "__main__":
    main()
